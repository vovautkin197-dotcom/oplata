/*
 * Логика страницы оплаты.
 *
 * Здесь намеренно нет ни цены, ни ссылки на Telegram, ни ключей ЮKassa:
 * всё это приходит с сервера. Код этого файла может прочитать любой
 * покупатель, открыв «Просмотр кода страницы».
 */

'use strict';

/* ======================= НАСТРОЙКА =======================
 * Единственное, что нужно поменять после публикации Apps Script.
 * Адрес выдаётся при развёртывании: «Развернуть» → «Новое развёртывание»
 * → «Веб-приложение». Заканчивается на /exec
 */
var АДРЕС_API = 'https://script.google.com/macros/s/AKfycbwa6eCoC1NJObYcESpaI-Xs_nBNnYjwgQ-pAGD-eOopvUlh9bvyeBn_AFCfbr0A8pRvKQ/exec';

/* Какой товар продаёт эта страница. Должен совпадать с ключом
 * в каталоге на сервере (файл 00_Config.gs). Цену страница не знает
 * и знать не должна — её выдаёт сервер. */
var ТОВАР = 'guide';

/* Сколько ждём подтверждения оплаты, прежде чем предложить
 * дождаться письма. Оплата по СБП иногда занимает до минуты. */
var ИНТЕРВАЛ_ОПРОСА_МС = 2000;
var МАКСИМУМ_ПОПЫТОК = 30;

/* ======================= КОРОТКИЕ ПОМОЩНИКИ ======================= */

function э(id) { return document.getElementById(id); }

var ЭКРАНЫ = ['экран-товар', 'экран-подготовка', 'экран-виджет',
              'экран-проверка', 'экран-успех', 'экран-ошибка'];

/** Показывает один экран и прячет остальные. */
function показать(идЭкрана) {
  ЭКРАНЫ.forEach(function (ид) {
    var узел = э(ид);
    if (узел) { узел.hidden = (ид !== идЭкрана); }
  });
  window.scrollTo({ top: 0, behavior: 'smooth' });
}

/** Сумма прописью для человека: 1490 → «1 490 ₽». */
function рубли(значение) {
  var число = Number(значение);
  if (!isFinite(число)) { return '—'; }
  // Целые суммы показываем без копеек: «1 490 ₽» читается легче, чем «1 490,00 ₽»
  var дробных = Number.isInteger(число) ? 0 : 2;
  return число.toLocaleString('ru-RU', {
    minimumFractionDigits: дробных,
    maximumFractionDigits: дробных
  }) + ' ₽';
}

/**
 * Запрос к Apps Script.
 *
 * Content-Type намеренно text/plain. При application/json браузер сначала
 * отправляет предварительный запрос OPTIONS, который Apps Script
 * обрабатывать не умеет, — вызов упал бы, не дойдя до нашего кода.
 * Тело при этом всё равно JSON, сервер разбирает его сам.
 */
function запрос(данные) {
  return fetch(АДРЕС_API, {
    method: 'POST',
    headers: { 'Content-Type': 'text/plain;charset=utf-8' },
    body: JSON.stringify(данные),
    redirect: 'follow'
  }).then(function (ответ) {
    if (!ответ.ok) { throw new Error('Сервер ответил ' + ответ.status); }
    return ответ.json();
  }).then(function (результат) {
    if (!результат || результат.ok !== true) {
      throw new Error((результат && результат.error) || 'Непонятный ответ сервера');
    }
    return результат;
  });
}

/** Понятная человеку формулировка вместо технической ошибки. */
function человеческаяОшибка(e) {
  var текст = String((e && e.message) || e);
  /* Сюда попадает и обычный обрыв связи, и отказ Apps Script.
     Когда скрипт не авторизован владельцем или развёрнут без доступа
     «для всех», Google отвечает страницей ошибки без заголовков CORS,
     и браузер не даёт прочитать даже её код — снаружи это неотличимо
     от пропавшей сети. Поэтому называем обе причины. */
  if (/Failed to fetch|NetworkError|Load failed/i.test(текст)) {
    return 'Не удалось связаться с сервером оплаты. Проверьте интернет ' +
           'и попробуйте снова. Если вы владелец сайта — запустите ' +
           'в Apps Script функцию «настроить» и разрешите ей доступ.';
  }
  if (/Сервер ответил 5\d\d/.test(текст)) {
    return 'Сервер временно недоступен. Попробуйте через минуту.';
  }
  /* 403 от Apps Script почти всегда означает одно и то же: владелец
     скрипта ещё не дал ему разрешения, либо после правки кода забыл
     сделать новое развёртывание. Покупателю это ничего не говорит,
     поэтому подсказка адресована владельцу сайта. */
  if (/Сервер ответил 40[13]/.test(текст)) {
    return 'Сервер оплаты пока не отвечает. Если вы владелец сайта — ' +
           'запустите в Apps Script функцию «настроить» и разрешите ей доступ, ' +
           'а после правок кода сделайте новое развёртывание.';
  }
  return текст;
}

/* ======================= ПАМЯТЬ О ЗАКАЗЕ =======================
 * Номер заказа держим в localStorage на случай, если человек оплатил
 * через приложение банка и вернулся на страницу без метки в адресе.
 *
 * Запись живёт два часа. Иначе тот, кто однажды передумал платить,
 * при следующем заходе попадал бы не на описание товара,
 * а на проверку своего давнего неоплаченного заказа.
 */

var КЛЮЧ_ЗАКАЗА = 'заказ';
var ЖИЗНЬ_ЗАПИСИ_МС = 2 * 60 * 60 * 1000;

function запомнитьЗаказ(номер) {
  try {
    localStorage.setItem(КЛЮЧ_ЗАКАЗА, JSON.stringify({
      номер: номер,
      время: Date.now()
    }));
  } catch (e) { /* режим инкогнито — обойдёмся меткой в адресе */ }
}

function вспомнитьЗаказ() {
  try {
    var запись = JSON.parse(localStorage.getItem(КЛЮЧ_ЗАКАЗА) || 'null');
    if (!запись || !запись.номер) { return null; }
    if (Date.now() - запись.время > ЖИЗНЬ_ЗАПИСИ_МС) {
      забытьЗаказ();
      return null;
    }
    return запись.номер;
  } catch (e) { return null; }
}

/** Номер заказа из адреса страницы — признак возврата после оплаты. */
function заказИзАдреса() {
  return new URLSearchParams(location.search).get('order');
}

function забытьЗаказ() {
  try { localStorage.removeItem(КЛЮЧ_ЗАКАЗА); } catch (e) { /* пусто */ }
}

/* ======================= ЭКРАН ТОВАРА ======================= */

var ценаТовара = null;

/* Номер заказа, с которым сейчас работает страница.
   Нужен, чтобы показать его в сообщении об ошибке: с этим номером
   покупатель обращается в поддержку. */
var текущийЗаказ = null;

/** Спрашивает у сервера название и цену. До ответа кнопка неактивна. */
function загрузитьТовар() {
  return запрос({ action: 'product', productId: ТОВАР })
    .then(function (ответ) {
      ценаТовара = ответ.price;
      э('цена').textContent = рубли(ответ.price);
      э('кнопка-оплатить').textContent = 'Оплатить ' + рубли(ответ.price);
      э('кнопка-оплатить').disabled = false;
    })
    .catch(function (e) {
      э('цена').textContent = '—';
      э('кнопка-оплатить').textContent = 'Цена недоступна';
      показатьОшибку('Цена не загрузилась. ' + человеческаяОшибка(e));
    });
}

/* ======================= ПРОВЕРКА ФОРМЫ ======================= */

function проверитьПочту() {
  var поле = э('почта');
  var значение = поле.value.trim();
  var ошибка = э('ошибка-почты');

  // Намеренно простая проверка: строгие регулярные выражения для e-mail
  // отсекают редкие, но действительные адреса. Настоящая проверка —
  // придёт ли письмо.
  var похоже = /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(значение);

  if (!значение) {
    ошибка.textContent = 'Укажите почту — на неё продублируем доступ';
  } else if (!похоже) {
    ошибка.textContent = 'Проверьте адрес: похоже, в нём опечатка';
  } else {
    ошибка.hidden = true;
    поле.removeAttribute('aria-invalid');
    return значение;
  }

  ошибка.hidden = false;
  поле.setAttribute('aria-invalid', 'true');
  поле.focus();
  return null;
}

function проверитьСогласие() {
  var галочка = э('согласие');
  var ошибка = э('ошибка-согласия');

  if (!галочка.checked) {
    ошибка.textContent = 'Без согласия с условиями оплату принять нельзя';
    ошибка.hidden = false;
    галочка.focus();
    return false;
  }
  ошибка.hidden = true;
  return true;
}

/* ======================= СОЗДАНИЕ ПЛАТЕЖА ======================= */

function начатьОплату(событие) {
  событие.preventDefault();

  var почта = проверитьПочту();
  if (!почта) { return; }
  if (!проверитьСогласие()) { return; }

  показать('экран-подготовка');

  /* Сумму не передаём намеренно: её взяли бы из браузера, а там её
     несложно подменить. Сервер берёт цену из своего каталога. */
  запрос({
    action: 'create',
    productId: ТОВАР,
    email: почта,
    returnUrl: адресВозврата()
  })
    .then(function (ответ) {
      текущийЗаказ = ответ.orderId;
      запомнитьЗаказ(ответ.orderId);
      показатьВиджет(ответ.confirmationToken, ответ.orderId, ответ.amount);
    })
    .catch(function (e) {
      показатьОшибку(человеческаяОшибка(e));
    });
}

/**
 * Куда ЮKassa вернёт покупателя после оплаты.
 *
 * Виджет перенаправляет всегда — этого требуют и подтверждение
 * по 3-D Secure, и оплата через приложение банка. Возвращаем человека
 * на эту же страницу с меткой заказа, чтобы она сама показала результат.
 */
function адресВозврата() {
  return location.origin + location.pathname;
}

/* ======================= ВИДЖЕТ ЮKASSA ======================= */

function показатьВиджет(токен, номерЗаказа, сумма) {
  if (typeof window.YooMoneyCheckoutWidget !== 'function') {
    показатьОшибку('Не загрузилась форма оплаты ЮKassa. ' +
      'Такое бывает из-за блокировщика рекламы — отключите его для этой страницы ' +
      'и попробуйте снова.');
    return;
  }

  э('виджет-сумма').textContent = 'К оплате ' + рубли(сумма);
  показать('экран-виджет');

  var виджет = new window.YooMoneyCheckoutWidget({
    confirmation_token: токен,
    return_url: адресВозврата() + '?order=' + encodeURIComponent(номерЗаказа),
    error_callback: function (ошибка) {
      показатьОшибку('Форма оплаты сообщила об ошибке: ' +
        ((ошибка && ошибка.error) || 'причина не указана'));
    }
  });

  /* Если версия виджета умеет сообщать об успехе событием — пользуемся:
     так человек увидит результат без перезагрузки страницы.
     Если не умеет, сработает возврат по return_url, и результат
     покажет проверка при загрузке. Оба пути ведут в одно место. */
  if (typeof виджет.on === 'function') {
    виджет.on('success', function () {
      проверятьОплату(номерЗаказа);
    });
  }

  виджет.render('payment-form');
}

/* ======================= ПРОВЕРКА ОПЛАТЫ ======================= */

/**
 * Спрашивает сервер, оплачен ли заказ, пока не получит ответ.
 *
 * Сервер не верит странице на слово: он сам обращается к API ЮKassa
 * за настоящим статусом платежа. Поэтому подделать оплату,
 * вызвав этот запрос вручную, не получится.
 */
function проверятьОплату(номерЗаказа, попытка) {
  попытка = попытка || 1;
  показать('экран-проверка');

  запрос({ action: 'status', orderId: номерЗаказа })
    .then(function (ответ) {
      if (ответ.status === 'paid') {
        забытьЗаказ();
        показатьУспех(ответ, номерЗаказа);
        return;
      }

      if (ответ.status === 'canceled') {
        забытьЗаказ();
        показатьОшибку('Платёж отменён. Деньги не списаны — можно попробовать снова.');
        return;
      }

      if (попытка >= МАКСИМУМ_ПОПЫТОК) {
        показатьОшибку(
          'Банк ещё обрабатывает платёж — это редко, но занимает до нескольких минут. ' +
          'Как только деньги дойдут, мы отправим доступ на вашу почту. ' +
          'Страницу можно закрыть.');
        return;
      }

      setTimeout(function () {
        проверятьОплату(номерЗаказа, попытка + 1);
      }, ИНТЕРВАЛ_ОПРОСА_МС);
    })
    .catch(function (e) {
      показатьОшибку(человеческаяОшибка(e));
    });
}

function показатьУспех(ответ, номерЗаказа) {
  э('ссылка-телеграм').href = ответ.telegramUrl;

  if (ответ.fileUrl) {
    э('ссылка-материалы').href = ответ.fileUrl;
    э('ссылка-материалы').hidden = false;
  }

  э('успех-почта').textContent = ответ.email || 'указанную почту';
  э('успех-заказ').textContent = номерЗаказа;

  показать('экран-успех');
}

function показатьОшибку(текст) {
  э('текст-ошибки').textContent = текст;
  э('ошибка-заказ').textContent = текущийЗаказ || '—';
  показать('экран-ошибка');
}

/**
 * Единственная проверка без опроса — для случая, когда номер заказа
 * взят из памяти браузера, а не из адреса.
 *
 * Человек мог просто зайти на страницу второй раз, ничего не оплатив.
 * Гонять его при этом по экрану «проверяем оплату» неправильно:
 * тихо спрашиваем один раз и, если оплаты нет, показываем описание товара.
 */
function тихаяПроверка(номерЗаказа) {
  запрос({ action: 'status', orderId: номерЗаказа })
    .then(function (ответ) {
      if (ответ.status === 'paid') {
        забытьЗаказ();
        показатьУспех(ответ, номерЗаказа);
      } else {
        текущийЗаказ = null;
        загрузитьТовар();
      }
    })
    .catch(function () {
      // Проверка была необязательной: молча показываем товар
      текущийЗаказ = null;
      загрузитьТовар();
    });
}

/* ======================= ЗАПУСК ======================= */

function запуск() {
  э('подвал-год').textContent = new Date().getFullYear();

  э('форма-оплаты').addEventListener('submit', начатьОплату);

  э('кнопка-назад').addEventListener('click', function () {
    показать('экран-товар');
  });

  э('кнопка-повторить').addEventListener('click', function () {
    забытьЗаказ();
    текущийЗаказ = null;
    // Метку заказа из адреса убираем, иначе перезагрузка снова
    // отправит человека проверять уже неудавшийся платёж.
    history.replaceState(null, '', адресВозврата());
    if (ценаТовара === null) { загрузитьТовар(); }
    показать('экран-товар');
  });

  // Прячем сообщение об ошибке, как только человек начал исправлять
  э('почта').addEventListener('input', function () {
    э('ошибка-почты').hidden = true;
    э('почта').removeAttribute('aria-invalid');
  });
  э('согласие').addEventListener('change', function () {
    э('ошибка-согласия').hidden = true;
  });

  if (АДРЕС_API.indexOf('ВСТАВЬТЕ') === 0) {
    показатьОшибку('Страница ещё не подключена к серверу: в файле app.js ' +
      'не заполнена настройка АДРЕС_API. См. «Инструкция_настройки.md», шаг 4.');
    return;
  }

  /* Метка в адресе — человек вернулся с оплаты. Выясняем результат
     настойчиво: банк мог ещё не завершить перевод. */
  var изАдреса = заказИзАдреса();
  if (изАдреса) {
    текущийЗаказ = изАдреса;
    проверятьОплату(изАдреса);
    return;
  }

  /* Метки нет, но браузер помнит недавний заказ: могло не сработать
     перенаправление из приложения банка. Проверяем один раз, тихо. */
  var изПамяти = вспомнитьЗаказ();
  if (изПамяти) {
    текущийЗаказ = изПамяти;
    тихаяПроверка(изПамяти);
    return;
  }

  загрузитьТовар();
}

document.addEventListener('DOMContentLoaded', запуск);
